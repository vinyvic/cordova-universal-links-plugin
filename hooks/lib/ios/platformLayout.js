/*
Detects the layout of the generated iOS platform.

cordova-ios 8+ always names the Xcode project "App" (platforms/ios/App.xcodeproj) and ships
per-configuration entitlements files (App/Entitlements-Debug.plist, App/Entitlements-Release.plist)
already wired to CODE_SIGN_ENTITLEMENTS. Older versions name the project after config.xml's <name>.
*/

var path = require('path');
var fs = require('fs');

var APP_PROJECT_NAME = 'App';
var ENTITLEMENTS_CONFIGURATIONS = ['Debug', 'Release'];

module.exports = {
  usesAppTemplate: usesAppTemplate,
  appTemplateEntitlementsFiles: appTemplateEntitlementsFiles
};

/**
 * @param {String} projectRoot - cordova project root
 * @return {Boolean} true when the iOS platform was generated by cordova-ios 8+
 */
function usesAppTemplate(projectRoot) {
  return fs.existsSync(path.join(projectRoot, 'platforms', 'ios', APP_PROJECT_NAME + '.xcodeproj'));
}

/**
 * @param {String} projectRoot - cordova project root
 * @return {String[]} absolute paths of the entitlements files used by the app target
 */
function appTemplateEntitlementsFiles(projectRoot) {
  return ENTITLEMENTS_CONFIGURATIONS.map(function(configuration) {
    return path.join(projectRoot, 'platforms', 'ios', APP_PROJECT_NAME, 'Entitlements-' + configuration + '.plist');
  });
}
